function drawUnlocks(ctx, t) {
  // "<PART> IN": a banner and a beam down the lane when a part enters (not the rim: the hook covers it)
  for (const l of LANES) {
    if (l.key === 'rim') continue;
    const t0 = l.entry * STEP;
    const k = t - t0;
    if (k < 0 || k > 1.5) continue;
    if (l.key === 'bass') continue;          // the realignment card announces the bass
    const a = window_(k, 0, 0.1, 1.1, 1.5);
    const flash = pulse(t, t0, 0.35);
    ctx.save();
    ctx.globalAlpha = 0.5 * flash; ctx.fillStyle = l.color; ctx.fillRect(l.x0, PLAY_TOP, LW, PLAY_BOT - PLAY_TOP);
    ctx.restore();
    const s = 1 + 0.2 * pulse(t, t0, 0.3);
    const label = `${l.name} IN`;
    ctx.save(); ctx.globalAlpha = a;
    ctx.translate(490, 760); ctx.scale(s, s);
    ctx.fillStyle = 'rgba(6,6,11,0.85)'; rrect(ctx, -300, -62, 600, 124, 20); ctx.fill();
    ctx.shadowColor = l.color; ctx.shadowBlur = 30;
    text(ctx, label, 0, 0, `800 72px ${FONT_D}`, l.color);
    ctx.restore();
  }
  // the full mix and the full combo
  for (const [lap, big, small] of [[FULL_MIX_LAP, 'FULL MIX', '6 of 6 parts'], [T.laps - 1, 'FULL COMBO', `${CUM[(T.laps - 1) * CYCLE]} HITS, NO MISSES`]]) {
    const t0 = stepTime(lap * CYCLE), k = t - t0;
    if (k < 0 || k > 1.8) continue;
    const a = window_(k, 0, 0.1, 1.4, 1.8), s = 1 + 0.2 * pulse(t, t0, 0.3);
    ctx.save(); ctx.globalAlpha = a; ctx.translate(490, 760); ctx.scale(s, s);
    ctx.fillStyle = 'rgba(6,6,11,0.85)'; rrect(ctx, -330, -80, 660, 160, 20); ctx.fill();
    ctx.shadowColor = COL.ok; ctx.shadowBlur = 30;
    text(ctx, big, 0, -22, `800 72px ${FONT_D}`, COL.ok);
    ctx.shadowBlur = 0;
    text(ctx, small, 0, 40, `700 28px ${MONO}`, COL.text);
    ctx.restore();
  }
}

