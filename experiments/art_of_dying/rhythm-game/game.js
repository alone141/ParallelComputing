// 45 — a rhythm game that plays the intro of Gojira's "The Art of Dying" (2008), round 2.
// Six lanes, one per part, unlocking one lap at a time. Every frame is a pure function of film
// time t (seconds), so the recorder can step the clock deterministically. The film is one loop:
// it starts with the click on step 0 at the hit line and ends 1/60 s before step 360 arrives.
'use strict';

const T = window.TIMELINE;                       // generated by rhythm.py
const STEP = T.step, CYCLE = T.cycle, N_STEPS = T.steps, LAP_S = CYCLE * STEP;
const RESTS = new Set(T.rests), SNARES = new Set(T.snares), KICK_RESTS = new Set(T.kickRests);
const GROUPS = T.groups, GROUP_START = T.groupStarts;
const REALIGN = T.realign, FULL_MIX_LAP = T.fullMixLap;
const DURATION = T.total;

// ---------- layout (1080 x 1920) ----------
const W = 1080, H = 1920;
const HIT_Y = 1340, PLAY_TOP = 390, PLAY_BOT = 1470;
const APPROACH = 1.6;
const SPEED = (HIT_Y - 420) / APPROACH;
const LANE_X0 = 100, LW = 130;
const COL = {
  bg: '#06060b', lap: '#FFFFFF', drift: '#FF4D6D', ok: '#5CFF8A', text: '#ECECF4', muted: '#8A8AA3',
  five: '#FFB13B', three: '#FF7A59', snare: '#FFFFFF', kick: '#FF6B4A',
};
const LANE_COLOUR = { rim: '#FFB13B', pulse: '#4FC3FF', ks: '#FF6B4A', ride: '#C8F56A', bass: '#FF5CC8', gtr: '#9D8CFF' };
const LANES = T.layers.map((l, i) => ({ ...l, i, x0: LANE_X0 + i * LW, x1: LANE_X0 + (i + 1) * LW, color: LANE_COLOUR[l.key] }));
const BY_KEY = Object.fromEntries(LANES.map((l) => [l.key, l]));
const LANE_X1 = LANES[LANES.length - 1].x1;
const FONT_D = '"Inter Display", "Inter", sans-serif';
const FONT = '"Inter", sans-serif';
const MONO = '"JetBrains Mono", monospace';

// ---------- helpers ----------
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const ease = (x) => 1 - Math.pow(1 - clamp(x, 0, 1), 3);
const smooth = (x) => { x = clamp(x, 0, 1); return x * x * (3 - 2 * x); };
const pulse = (t, t0, d) => (t < t0 ? 0 : Math.max(0, 1 - (t - t0) / d));
function window_(t, a, b, c, d) {
  if (t < a || t > d) return 0;
  if (t < b) return smooth((t - a) / (b - a));
  if (t < c) return 1;
  return 1 - smooth((t - c) / (d - c));
}
function rrect(ctx, x, y, w, h, r) {
  r = Math.min(r, Math.abs(w) / 2, Math.abs(h) / 2);
  ctx.beginPath();
  ctx.moveTo(x + r, y); ctx.lineTo(x + w - r, y); ctx.arcTo(x + w, y, x + w, y + r, r);
  ctx.lineTo(x + w, y + h - r); ctx.arcTo(x + w, y + h, x + w - r, y + h, r);
  ctx.lineTo(x + r, y + h); ctx.arcTo(x, y + h, x, y + h - r, r);
  ctx.lineTo(x, y + r); ctx.arcTo(x, y, x + r, y, r); ctx.closePath();
}
function fitFont(ctx, s, font, maxW) {
  const m = font.match(/^(.*?)(\d+)px(.*)$/);
  let size = Number(m[2]);
  for (;;) {
    const f = `${m[1]}${size}px${m[3]}`;
    ctx.font = f;
    if (ctx.measureText(s).width <= maxW || size <= 18) return f;
    size -= 1;
  }
}
function text(ctx, s, x, y, font, color, align = 'center', alpha = 1) {
  ctx.save(); ctx.globalAlpha *= alpha; ctx.font = font; ctx.fillStyle = color;
  ctx.textAlign = align; ctx.textBaseline = 'middle'; ctx.fillText(s, x, y); ctx.restore();
}
const stepTime = (n) => n * STEP;
const noteY = (n, t) => HIT_Y - (stepTime(n) - t) * SPEED;

// ---------- the music model (mirrors rhythm.py) ----------
function hitsAt(key, n) {
  const c = n % CYCLE;
  if (key === 'rim') return RESTS.has(c) ? [] : ['click'];
  if (key === 'bass') return RESTS.has(c) ? [] : ['note'];
  if (key === 'pulse') return n % 4 === T.beatPhase ? ['pulse'] : [];
  if (key === 'ks') return SNARES.has(c) ? ['snare'] : KICK_RESTS.has(c) ? [] : ['kick'];
  if (key === 'ride') return n % 4 === T.beatPhase ? ['bell'] : n % 4 === (T.beatPhase + 2) % 4 ? ['ride'] : [];
  if (key === 'gtr') return ['chug'];
  return [];
}
function present(l, n) {
  n = ((n % N_STEPS) + N_STEPS) % N_STEPS;            // the film loops
  return n >= l.entry && (l.peel == null || n < l.peel);
}
function focusWeight(l, t) {
  const s = l.entry * STEP, e = s + LAP_S, E = T.ease;
  if (l.key === 'rim') return t < e + E ? 1 - smooth((t - (e - E)) / E) : 0;
  if (t < s - E || t >= e + E) return 0;
  return smooth((t - s) / E) * (1 - smooth((t - (e - E)) / E));
}
function background(l, t) {
  let m = 0;
  for (const o of LANES) if (o !== l) m = Math.max(m, focusWeight(o, t));
  return m;
}
function presence(l, t) {
  // 0..1 for the picture: in from its entry (instant), out over 0.45 s after its peel
  if (t < l.entry * STEP) return 0;
  if (l.peel == null) return 1;
  return 1 - smooth((t - l.peel * STEP) / 0.45);
}
function laneOpacity(l, t) {
  return presence(l, t) * (1 - (1 - T.focusDim) * background(l, t));
}

// notes: { n, lane, kind, feet } for n in [0, N_STEPS + 20) (the tail shows the loop's first notes)
const NOTES = [];
{
  let foot = 0;
  for (let n = 0; n < N_STEPS + 20; n++) {
    for (const l of LANES) {
      const on = present(l, n);
      if (l.key === 'pulse' && n % 4 === T.beatPhase) { NOTES.push({ n, lane: l, kind: on ? 'pulse' : 'ghost' }); continue; }
      if (!on) continue;
      for (const kind of hitsAt(l.key, n)) {
        const note = { n, lane: l, kind };
        if (kind === 'kick') { note.foot = foot; foot ^= 1; }
        if (kind === 'note' && RESTS.has((n + 1) % CYCLE)) note.hold = 1;
        NOTES.push(note);
      }
    }
  }
}
// cumulative hits per step (the combo)
const CUM = [0];
for (let n = 0; n < N_STEPS; n++) {
  let c = 0;
  for (const l of LANES) if (present(l, n)) c += hitsAt(l.key, n).length;
  CUM.push(CUM[n] + c);
}
function combo(t) {
  if (t < 0) return 0;
  return CUM[Math.min(Math.floor(t / STEP + 1e-6) + 1, N_STEPS)];
}
function lastHit(l, t) {
  // time of the lane's last hit before t (null if none in the last 8 steps)
  const n = Math.floor(t / STEP + 1e-6);
  for (let i = n; i >= 0 && i > n - 8; i--) {
    if (l.key === 'pulse' ? i % 4 === T.beatPhase : present(l, i) && hitsAt(l.key, i).length) return stepTime(i);
  }
  return null;
}

