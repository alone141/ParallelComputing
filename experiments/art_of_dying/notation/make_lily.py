"""Generate the LilyPond reference score from pattern.py and engrave it.

Three scores: the 45/16 cycle (rim clicks), the 45/16 kit groove (two
voices), and the tab's view of bars 12-22: ten bars of 4/4 and one of 5/4
with the tribal hit on every beat.  Used to cross-check the film's engraver.

    python3 make_lily.py        # writes lilypond/art_of_dying_intro.{ly,png,pdf}
"""
import os, subprocess
import pattern as P

HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.join(HERE, "lilypond")


def rim_cycle():
    """Manual beams per group, with stemlets over the rests."""
    out = []
    for g, s in zip(P.GROUPS, P.GROUP_START):
        toks = []
        for k in range(g):
            t = s + k
            toks.append("ss" if P.RIM[t] else "r")
        toks[0] += "16["
        toks[-1] += "]"
        out.append(" ".join(toks))
    return "  " + "\n  ".join(out)


def feet():
    out = []
    for g, s in zip(P.GROUPS, P.GROUP_START):
        toks = ["bd" if (s + k) in P.KICK_SLOTS else "r" for k in range(g)]
        toks[0] += "16["
        toks[-1] += "]"
        out.append(" ".join(toks))
    return "  " + "\n  ".join(out)


def hands(beat_off=0):
    """Ride eighths with the bell on the beat, snare on its slots, rests elsewhere."""
    out = []
    for g, s in zip(P.GROUPS, P.GROUP_START):
        toks = []
        for k in range(g):
            t = s + k
            ev = []
            if (t - beat_off) % 4 == 0:
                ev.append("cymc" if t == 0 else "rb")
            elif (t - beat_off) % 4 == 2:
                ev.append("cymr")
            if t in P.SNARE_SLOTS:
                ev.append("sn")
            if not ev:
                toks.append("r")
            elif len(ev) == 1:
                toks.append(ev[0])
            else:
                toks.append("<" + " ".join(ev) + ">")
        toks[0] += "16"
        out.append(" ".join(toks))
    return "  " + "\n  ".join(out)


def tab_view():
    """Bars 12-22 of the record: the rim pattern plus the tribal hit on every
    beat, written in 4/4 (ten bars) and 5/4 (one bar).  180 sixteenths."""
    bars = []
    pos = 0
    for nb in P.TAB_BARS:
        toks = []
        for beat in range(nb):
            for k in range(4):
                t = pos % 45
                ev = []
                if P.RIM[t]:
                    ev.append("ss")
                if k == 0:
                    ev += ["bd", "tomfl"]
                if not ev:
                    toks.append("r16")
                elif len(ev) == 1:
                    toks.append(ev[0] + "16")
                else:
                    toks.append("<" + " ".join(ev) + ">16")
                pos += 1
        bars.append(" ".join(toks))
    body = " |\n  ".join(bars)
    return "  \\time 4/4\n  " + body.replace(bars[-1], "\\time 5/4 " + bars[-1]) + " |"


LY = r'''\version "2.24.0"
%% Gojira, "The Art of Dying" (The Way of All Flesh, 2008): the drum intro.
%% Independent study, not affiliated with the band or label.  Generated by make_lily.py.

\header {
  title = "The Art of Dying — intro"
  subtitle = "Gojira, The Way of All Flesh (2008) · drums: Mario Duplantier · 140 bpm"
  tagline = "independent study · after Songsterr / R. Pannier / Y. Gabay · engraved with LilyPond"
}

#(set-global-staff-size 19)
\paper {
  paper-width = 300\mm
  paper-height = 240\mm
  indent = 14\mm
  top-margin = 8\mm
  left-margin = 8\mm
  right-margin = 8\mm
}

fortyfive = {
  \time 45/16
  \set Timing.beatStructure = 5,5,5,3,3,3,5,5,5,3,3
  \set Timing.beamExceptions = #'()
  \override Stem.stemlet-length = #0.75
}

\score {
  \header { piece = "bars 1–11: side stick alone (one 45/16 cycle, repeated)" }
  \new DrumStaff { \fortyfive \tempo 4 = 140 \repeat volta 11 { \drummode {
%(rim)s
  } } }
  \layout { }
}

\score {
  \header { piece = "bars 42+: the whole band (hands up, feet down); the bell drifts one sixteenth per lap" }
  \new DrumStaff <<
    \fortyfive
    \new DrumVoice { \voiceOne \repeat volta 2 { \drummode {
%(hands)s
    } } }
    \new DrumVoice { \voiceTwo \repeat volta 2 { \drummode {
%(feet)s
    } } }
  >>
  \layout { }
}

\score {
  \header { piece = "bars 12–22 as the tab writes them: ten bars of 4/4 and one of 5/4 (45 beats = four laps of the cycle)" }
  \new DrumStaff { \tempo 4 = 140 \drummode {
%(tab)s
  } }
  \layout { }
}
'''


def main():
    os.makedirs(OUTDIR, exist_ok=True)
    src = LY % dict(rim=rim_cycle(), hands=hands(), feet=feet(), tab=tab_view())
    path = os.path.join(OUTDIR, "art_of_dying_intro.ly")
    open(path, "w").write(src)
    import lilypond
    r = subprocess.run([lilypond.executable(), "-dno-point-and-click", "--png", "--pdf",
                        "-dresolution=150", "-o", os.path.join(OUTDIR, "art_of_dying_intro"), path],
                       capture_output=True, text=True)
    print(r.stderr[-800:])
    print("ok" if r.returncode == 0 else "FAILED")


if __name__ == "__main__":
    main()
